// Package cgen emits C99 from a checked Quoin program.
//
// Code shape:
//   - every Quoin call, fallible call and register read is hoisted into a
//     temporary in source order, which gives Quoin a defined left-to-right
//     evaluation order that C itself does not have;
//   - fallible functions return ql_err and write their value through a
//     trailing out-parameter;
//   - grow-array locals live in a function's frame on the static data stack,
//     claimed at entry and released on every return;
//   - only the runtime checks the checker marked are emitted.
package cgen

import (
	_ "embed"
	"fmt"
	"math/big"
	"strings"

	"github.com/amken3d/quoin/internal/ast"
	"github.com/amken3d/quoin/internal/check"
	"github.com/amken3d/quoin/internal/types"
)

// RuntimeHeader is quoin_rt.h, written next to the generated C.
//
//go:embed quoin_rt.h
var RuntimeHeader string

// Options control emission.
type Options struct {
	Source    string // primary source file name, for the banner
	Lines     bool   // emit #line directives mapping C back to Quoin source
	DataStack int64  // bytes for the shared data stack (from the stack report)
	CallStack int64  // worst-case call stack bytes (for the linker fragment)
	StackSrc  string // "est" or "su"
}

type gen struct {
	p   *check.Program
	opt Options

	out     *strings.Builder
	types   strings.Builder
	helpers strings.Builder
	done    map[string]bool
	ind     int
	tmp     int
	fn      *types.Fn
	file    string
	reach   map[*types.Fn]bool
}

// Generate returns the C translation unit.
func Generate(p *check.Program, opt Options) string {
	g := &gen{p: p, opt: opt, done: map[string]bool{}, reach: map[*types.Fn]bool{}}
	for _, e := range p.Entries {
		g.markReach(e)
	}
	var body strings.Builder
	g.out = &body

	// Named types first, in declaration order, so their typedefs and enum
	// constants appear even when only used in signatures.
	for _, t := range p.Named {
		g.ctype(t)
	}
	var protos, defs strings.Builder
	for _, decl := range p.Decls {
		fd, ok := decl.(*ast.FnDecl)
		if !ok || fd.Fn == nil || !g.reach[fd.Fn] {
			continue
		}
		if fd.Fn.Main {
			continue
		}
		protos.WriteString(g.prototype(fd.Fn) + ";\n")
	}
	for _, decl := range p.Decls {
		fd, ok := decl.(*ast.FnDecl)
		if !ok || fd.Fn == nil || !g.reach[fd.Fn] || fd.Extern {
			continue
		}
		g.out = &defs
		g.function(fd)
	}
	var globals strings.Builder
	for _, c := range p.Consts {
		if c.Sym == nil || c.Sym.Type == nil || c.Sym.Type.Kind == types.Invalid || c.Sym.Const != nil {
			continue
		}
		if c.Sym.Type.Kind == types.Bool || c.Sym.Type.Kind == types.Enum {
			continue // inlined
		}
		fmt.Fprintf(&globals, "static const %s %s = %s;\n", g.ctype(c.Sym.Type), c.Sym.CName, g.constInit(c.Value, c.Sym.Type))
	}
	for _, decl := range p.Decls {
		vd, ok := decl.(*ast.VarDecl)
		if !ok || vd.Sym == nil || vd.Sym.Type == nil || vd.Sym.Type.Kind == types.Invalid {
			continue
		}
		if vd.Value != nil {
			fmt.Fprintf(&globals, "static %s %s = %s;\n", g.ctype(vd.Sym.Type), vd.Sym.CName, g.constInit(vd.Value, vd.Sym.Type))
		} else {
			fmt.Fprintf(&globals, "static %s %s;\n", g.ctype(vd.Sym.Type), vd.Sym.CName)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by quoinc from %s. Do not edit.\n", opt.Source)
	fmt.Fprintf(&b, " * Worst case: call stack %dB, data stack %dB (src=%s). */\n", opt.CallStack, opt.DataStack, opt.StackSrc)
	b.WriteString("#include \"quoin_rt.h\"\n")
	b.WriteString("#ifndef QL_FN\n#define QL_FN static /* benchmarks: -DQL_FN='static __attribute__((noinline))' */\n#endif\n\n")
	b.WriteString("/* ---- error codes ---- */\n")
	for _, e := range p.ErrTags {
		fmt.Fprintf(&b, "#define %s ((ql_err)%su)\n", e.CName, e.Const)
	}
	b.WriteString("\n/* ---- types ---- */\n")
	b.WriteString(g.types.String())
	if g.helpers.Len() > 0 {
		b.WriteString("\n/* ---- queues ---- */\n")
		b.WriteString(g.helpers.String())
	}
	if len(p.Periphs) > 0 {
		b.WriteString("\n/* ---- peripherals ---- */\n")
		for _, d := range p.Periphs {
			if d.Sym == nil || d.Sym.Addr == nil || d.Sym.Type == nil || d.Sym.Type.Kind != types.Regs {
				continue
			}
			fmt.Fprintf(&b, "#define %s ((qn_%s *)0x%08Xu)\n", d.Sym.CName, d.Sym.Type.Name, d.Sym.Addr.Uint64())
		}
	}
	b.WriteString("\n/* ---- data stack ---- */\n")
	fmt.Fprintf(&b, "#define QL_DATA_STACK_BYTES %du\n", opt.DataStack)
	if opt.DataStack > 0 {
		b.WriteString("static uint8_t ql_dstack[QL_DATA_STACK_BYTES] QL_ALIGN8 QL_DSTACK_SECTION;\n")
		b.WriteString("/* volatile: an isr claims frames above this pointer and restores it\n * before returning, so every store must reach memory before use. */\n")
		b.WriteString("static uint8_t *volatile ql_dsp = ql_dstack;\n")
		b.WriteString("#define QL_DFRAME(n) uint8_t *const ql_df = ql_dsp; ql_dsp = ql_df + (n); \\\n")
		b.WriteString("    QL_CHECK(ql_dsp <= ql_dstack + QL_DATA_STACK_BYTES)\n")
	}
	b.WriteString("\nQL_WEAK QL_NORETURN void ql_trap(void) { QL_TRAP_BODY(); }\n")
	if globals.Len() > 0 {
		b.WriteString("\n/* ---- globals ---- */\n")
		b.WriteString(globals.String())
	}
	if protos.Len() > 0 {
		b.WriteString("\n/* ---- prototypes ---- */\n")
		b.WriteString(protos.String())
	}
	b.WriteString("\n/* ---- functions ---- */\n")
	b.WriteString(defs.String())
	return b.String()
}

// LinkerFragment returns a GNU ld fragment exposing the worst-case numbers.
func LinkerFragment(call, data int64) string {
	return fmt.Sprintf(`/* Generated by quoinc. INCLUDE this from your linker script.
 * The data stack is a static array in .bss, so RAM overflow already fails
 * the link. The call stack needs an explicit check against your script's
 * stack symbols, for example (CMSIS / pico-sdk scripts):
 *
 *   ASSERT(__StackTop - __StackLimit >= __quoin_call_stack_bytes,
 *          "quoin: call stack smaller than the proven worst case")
 */
PROVIDE(__quoin_call_stack_bytes = %d);
PROVIDE(__quoin_data_stack_bytes = %d);
`, call, data)
}

func (g *gen) markReach(fn *types.Fn) {
	if g.reach[fn] {
		return
	}
	g.reach[fn] = true
	for _, c := range fn.Calls {
		g.markReach(c.Callee)
	}
}

// ---- output helpers --------------------------------------------------------

func (g *gen) line(format string, args ...any) {
	g.out.WriteString(strings.Repeat("    ", g.ind))
	fmt.Fprintf(g.out, format, args...)
	g.out.WriteString("\n")
}

func (g *gen) lineDirective(line int) {
	if g.opt.Lines && line > 0 {
		fmt.Fprintf(g.out, "#line %d \"%s\"\n", line, g.file)
	}
}

func (g *gen) newTemp() string {
	g.tmp++
	return fmt.Sprintf("ql_t%d", g.tmp)
}

// temp emits `T name = init;` and returns the name.
func (g *gen) temp(ct, init string) string {
	n := g.newTemp()
	g.line("%s %s = %s;", ct, n, init)
	return n
}

// capture runs f with output redirected, at one extra indent level.
func (g *gen) capture(f func()) string {
	saved := g.out
	var buf strings.Builder
	g.out = &buf
	g.ind++
	f()
	g.ind--
	g.out = saved
	return buf.String()
}

// ---- types -----------------------------------------------------------------

func mangle(t *types.Type) string {
	switch t.Kind {
	case types.Bool:
		return "bool"
	case types.Int:
		return t.String()
	case types.Enum, types.Struct, types.Regs:
		return t.Name
	case types.ErrorVal:
		return "err"
	case types.Array:
		return fmt.Sprintf("a%d_%s", t.Len, mangle(t.Elem))
	case types.Slice:
		return "s_" + mangle(t.Elem)
	case types.Grow:
		return fmt.Sprintf("g%d_%s", t.Len, mangle(t.Elem))
	case types.Queue:
		return fmt.Sprintf("q%d_%s", t.Len, mangle(t.Elem))
	}
	return "x"
}

func intC(bits int, signed bool) string {
	if signed {
		return fmt.Sprintf("int%d_t", types.CBits(bits))
	}
	return fmt.Sprintf("uint%d_t", types.CBits(bits))
}

// ctype returns the C type name for t, emitting its typedef on first use.
func (g *gen) ctype(t *types.Type) string {
	switch t.Kind {
	case types.Void:
		return "void"
	case types.Bool:
		return "bool"
	case types.Int:
		return intC(t.Bits, t.Signed)
	case types.ErrorVal:
		return "ql_err"
	case types.Enum:
		if !g.done[t.Name] {
			g.done[t.Name] = true
			fmt.Fprintf(&g.types, "/* enum %s: %s */\n", t.Name, t.Base)
			for _, m := range t.Members {
				fmt.Fprintf(&g.types, "#define qn_%s_%s %s\n", t.Name, m.Name, lit(m.Value, t.Base))
			}
		}
		return g.ctype(t.Base)
	}
	name := ""
	switch t.Kind {
	case types.Struct, types.Regs:
		name = "qn_" + t.Name
	default:
		name = "ql_" + mangle(t)
	}
	if g.done[name] {
		return name
	}
	g.done[name] = true
	var b strings.Builder
	switch t.Kind {
	case types.Struct:
		var fields []string
		for _, f := range t.Fields {
			fields = append(fields, fmt.Sprintf("    %s %s;\n", g.ctype(f.Type), check.CName(f.Name)))
		}
		fmt.Fprintf(&b, "typedef struct %s {\n%s} %s;\n", name, strings.Join(fields, ""), name)
		size, _ := t.Layout()
		fmt.Fprintf(&b, "QL_STATIC_ASSERT(sizeof(%s) == %d, %s_size);\n", name, size, name)
	case types.Regs:
		fmt.Fprintf(&b, "typedef struct %s {\n", name)
		var off int64
		pad := 0
		for _, r := range t.Regs {
			if r.Offset > off {
				pad++
				fmt.Fprintf(&b, "    uint8_t ql_pad%d[%d];\n", pad, r.Offset-off)
			}
			fmt.Fprintf(&b, "    volatile %s %s; /* 0x%02X */\n", intC(r.Type.Bits, false), r.Name, r.Offset)
			off = r.Offset + int64(r.Type.Bits/8)
		}
		fmt.Fprintf(&b, "} %s;\n", name)
		for _, r := range t.Regs {
			fmt.Fprintf(&b, "QL_STATIC_ASSERT(offsetof(%s, %s) == 0x%02X, %s_%s);\n", name, r.Name, r.Offset, name, r.Name)
		}
	case types.Array:
		et := g.ctype(t.Elem)
		fmt.Fprintf(&b, "typedef struct { %s a[%d]; } %s;\n", et, t.Len, name)
	case types.Slice:
		et := g.ctype(t.Elem)
		fmt.Fprintf(&b, "typedef struct { %s *ptr; uint32_t len; } %s;\n", et, name)
	case types.Grow:
		et := g.ctype(t.Elem)
		size, _ := t.Layout()
		fmt.Fprintf(&b, "typedef struct { uint32_t len; %s data[%d]; } %s;\n", et, t.Len, name)
		fmt.Fprintf(&b, "QL_STATIC_ASSERT(sizeof(%s) == %d, %s_size);\n", name, size, name)
	case types.Queue:
		et := g.ctype(t.Elem)
		slots := t.Len + 1
		fmt.Fprintf(&b, "typedef struct { volatile uint32_t head; volatile uint32_t tail; %s buf[%d]; } %s;\n", et, slots, name)
		m := mangle(t)
		fmt.Fprintf(&g.helpers, `static QL_INLINE ql_err ql_qsend_%[1]s(%[2]s *q, %[3]s v) {
    uint32_t h = q->head;
    uint32_t n = h + 1u == %[4]du ? 0u : h + 1u;
    if (n == q->tail) return QE_Full;
    q->buf[h] = v;
    QL_BARRIER();
    q->head = n;
    return 0;
}
static QL_INLINE ql_err ql_qrecv_%[1]s(%[2]s *q, %[3]s *out) {
    uint32_t t = q->tail;
    if (t == q->head) return QE_Empty;
    QL_BARRIER();
    *out = q->buf[t];
    QL_BARRIER();
    q->tail = t + 1u == %[4]du ? 0u : t + 1u;
    return 0;
}
`, m, name, et, slots)
	}
	g.types.WriteString(b.String())
	return name
}

func (g *gen) paramDecl(p *types.Symbol) string {
	switch p.Type.Kind {
	case types.Grow, types.Regs:
		return fmt.Sprintf("%s *%s", g.ctype(p.Type), p.CName)
	}
	return fmt.Sprintf("%s %s", g.ctype(p.Type), p.CName)
}

func (g *gen) prototype(fn *types.Fn) string {
	var ps []string
	for _, p := range fn.Params {
		ps = append(ps, g.paramDecl(p))
	}
	ret := g.ctype(fn.Ret)
	if fn.Fallible() {
		if fn.Ret.Kind != types.Void {
			ps = append(ps, ret+" *ql_out")
		}
		ret = "ql_err"
	}
	if len(ps) == 0 {
		ps = []string{"void"}
	}
	storage := "QL_FN "
	switch {
	case fn.Main:
		return "int main(void)"
	case fn.Extern:
		storage = "extern "
	case fn.ISR:
		storage = ""
	}
	return fmt.Sprintf("%s%s %s(%s)", storage, ret, fn.CName, strings.Join(ps, ", "))
}

// ---- literals --------------------------------------------------------------

var (
	int32Min = big.NewInt(-1 << 31)
	int32Max = big.NewInt(1<<31 - 1)
	uint32M  = new(big.Int).SetUint64(1<<32 - 1)
	int64Min = new(big.Int).Lsh(big.NewInt(-1), 63)
	int64Max = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 63), big.NewInt(1))
)

// lit renders constant v as a C expression of type t.
func lit(v *big.Int, t *types.Type) string {
	if t.Kind == types.Enum {
		t = t.Base
	}
	switch t.Kind {
	case types.Bool:
		if v.Sign() != 0 {
			return "true"
		}
		return "false"
	case types.Int:
		ct := intC(t.Bits, t.Signed)
		var s string
		switch {
		case !t.Signed && v.Cmp(uint32M) <= 0:
			s = v.String() + "u"
		case !t.Signed:
			s = v.String() + "ull"
		case v.Cmp(int64Min) == 0:
			s = "(-9223372036854775807ll - 1)"
		case v.Cmp(int32Min) >= 0 && v.Cmp(int32Max) <= 0:
			s = v.String()
		default:
			s = v.String() + "ll"
		}
		if ct == "uint32_t" && !strings.HasSuffix(s, "ll") || ct == "int32_t" && !strings.HasSuffix(s, "ll") {
			if v.Sign() < 0 {
				return "(" + s + ")"
			}
			return s
		}
		return fmt.Sprintf("((%s)%s)", ct, s)
	}
	if v.Sign() < 0 {
		return "(" + v.String() + "ll)"
	}
	return v.String() + "ll"
}

func minLit(t *types.Type) string { return lit(t.Min(), types.IntT(64, true)) }

func maxLit(t *types.Type) string {
	if !t.Signed {
		return lit(t.Max(), types.IntT(64, false))
	}
	return lit(t.Max(), types.IntT(64, true))
}

// constInit renders a static initializer.
func (g *gen) constInit(e ast.Expr, t *types.Type) string {
	if k := e.Info().Const; k != nil {
		return lit(k, t)
	}
	switch x := e.(type) {
	case *ast.Paren:
		return g.constInit(x.X, t)
	case *ast.BoolLit:
		if x.Val {
			return "true"
		}
		return "false"
	case *ast.ArrayLit:
		var els []string
		for _, el := range x.Elems {
			els = append(els, g.constInit(el, t.Elem))
		}
		return "{{" + strings.Join(els, ", ") + "}}"
	case *ast.StructLit:
		var fs []string
		for _, fi := range x.Fields {
			var ft *types.Type
			for _, f := range t.Fields {
				if f.Name == fi.Name {
					ft = f.Type
				}
			}
			fs = append(fs, fmt.Sprintf(".%s = %s", check.CName(fi.Name), g.constInit(fi.Value, ft)))
		}
		if len(fs) == 0 {
			return "{0}"
		}
		return "{" + strings.Join(fs, ", ") + "}"
	case *ast.Ident:
		if d, ok := x.Sym.Decl.(*ast.ConstDecl); ok {
			return g.constInit(d.Value, t)
		}
	}
	return "{0}"
}

// ---- functions -------------------------------------------------------------

func (g *gen) function(fd *ast.FnDecl) {
	fn := fd.Fn
	g.fn = fn
	g.tmp = 0
	g.file = fd.P.File
	g.out.WriteString("\n")
	g.lineDirective(fd.P.Line)
	g.line("%s {", g.prototype(fn))
	g.ind++
	if fn.DataFrame > 0 {
		g.line("QL_DFRAME(%d);", fn.DataFrame)
	}
	for _, w := range fd.Where {
		g.lineDirective(w.EPos().Line)
		g.line("QL_CHECK(%s);", g.expr(w))
	}
	g.stmts(fd.Body.Stmts)
	if !terminates(fd.Body) {
		switch {
		case fn.Main:
			g.release()
			g.line("return 0;")
		case fn.Fallible():
			g.release()
			g.line("return 0;")
		default:
			g.release()
		}
	}
	g.ind--
	g.line("}")
	g.fn = nil
}

func (g *gen) release() {
	if g.fn.DataFrame > 0 {
		g.line("ql_dsp = ql_df;")
	}
}

func (g *gen) block(b *ast.Block) {
	g.stmts(b.Stmts)
}

func (g *gen) stmts(ss []ast.Stmt) {
	for _, s := range ss {
		g.stmt(s)
	}
}

func zeroInit(t *types.Type) string {
	switch t.Kind {
	case types.Bool:
		return "false"
	case types.Int, types.Enum, types.ErrorVal:
		return "0"
	}
	return "{0}"
}

func (g *gen) stmt(s ast.Stmt) {
	g.lineDirective(s.SPos().Line)
	switch s := s.(type) {
	case *ast.Block:
		g.line("{")
		g.ind++
		g.block(s)
		g.ind--
		g.line("}")
	case *ast.DefineStmt:
		sym := s.Sym
		if sym == nil {
			return
		}
		v := g.exprAs(s.Value, sym.Type)
		switch sym.Type.Kind {
		case types.Regs:
			g.line("%s *const %s = %s;", g.ctype(sym.Type), sym.CName, v)
		case types.Slice:
			g.line("const %s %s = %s;", g.ctype(sym.Type), sym.CName, v)
		default:
			g.line("%s %s = %s;", g.ctype(sym.Type), sym.CName, v)
		}
	case *ast.VarStmt:
		sym := s.Sym
		if sym == nil {
			return
		}
		ct := g.ctype(sym.Type)
		switch {
		case sym.OnDataStack:
			g.line("%s *const %s = (%s *)(void *)(ql_df + %d);", ct, sym.CName, ct, sym.DataOff)
			g.line("%s->len = 0;", sym.CName)
		case s.Value != nil:
			g.line("%s %s = %s;", ct, sym.CName, g.exprAs(s.Value, sym.Type))
		default:
			g.line("%s %s = %s;", ct, sym.CName, zeroInit(sym.Type))
		}
	case *ast.AssignStmt:
		g.assign(s)
	case *ast.ExprStmt:
		g.exprStmt(s.X)
	case *ast.ReturnStmt:
		g.ret(s)
	case *ast.IfStmt:
		g.ifStmt(s, false)
	case *ast.ForStmt:
		g.forStmt(s)
	case *ast.BranchStmt:
		g.line("%s;", s.Tok)
	}
}

func (g *gen) ifStmt(s *ast.IfStmt, isElse bool) {
	cond := g.expr(s.Cond)
	g.line("if (%s) {", cond)
	g.ind++
	g.block(s.Then)
	g.ind--
	switch e := s.Else.(type) {
	case nil:
		g.line("}")
	case *ast.Block:
		g.line("} else {")
		g.ind++
		g.block(e)
		g.ind--
		g.line("}")
	case *ast.IfStmt:
		// The else-if condition may need hoisted temporaries; they belong
		// inside the else branch so they only run when reached.
		g.line("} else {")
		g.ind++
		g.lineDirective(e.P.Line)
		g.ifStmt(e, true)
		g.ind--
		g.line("}")
	}
}

func (g *gen) forStmt(s *ast.ForStmt) {
	switch s.Kind {
	case ast.ForEver:
		g.line("for (;;) {")
		g.ind++
		g.block(s.Body)
		g.ind--
		g.line("}")
	case ast.ForCond:
		var cond string
		pre := g.capture(func() { cond = g.expr(s.Cond) })
		if pre == "" {
			g.line("while (%s) {", cond)
		} else {
			g.line("for (;;) {")
			g.out.WriteString(pre)
			g.ind++
			g.line("if (!(%s)) break;", cond)
			g.ind--
		}
		g.ind++
		g.block(s.Body)
		g.ind--
		g.line("}")
	case ast.ForRange:
		if s.VarSym == nil {
			return
		}
		ct := g.ctype(s.VarSym.Type)
		lo := g.expr(s.Lo)
		hi := g.expr(s.Hi)
		g.line("{")
		g.ind++
		g.line("const %s ql_hi = %s;", ct, hi)
		g.line("for (%s %s = %s; %s < ql_hi; %s++) {", ct, s.VarSym.CName, lo, s.VarSym.CName, s.VarSym.CName)
		g.ind++
		g.block(s.Body)
		g.ind--
		g.line("}")
		g.ind--
		g.line("}")
	case ast.ForEach:
		if s.VarSym == nil {
			return
		}
		it := s.Iter.Info().Type
		st := &types.Type{Kind: types.Slice, Elem: it.Elem}
		var view string
		if it.Kind == types.Array && !addressable(s.Iter) {
			tmp := g.temp(g.ctype(it), g.expr(s.Iter))
			view = fmt.Sprintf("(%s){ %s.a, %du }", g.ctype(st), tmp, it.Len)
		} else {
			view = g.exprAs(s.Iter, st)
		}
		g.line("{")
		g.ind++
		g.line("const %s ql_it = %s;", g.ctype(st), view)
		g.line("for (uint32_t ql_i = 0; ql_i < ql_it.len; ql_i++) {")
		g.ind++
		if s.IndexSym != nil {
			g.line("const uint32_t %s = ql_i;", s.IndexSym.CName)
		}
		g.line("const %s %s = ql_it.ptr[ql_i];", g.ctype(s.VarSym.Type), s.VarSym.CName)
		g.block(s.Body)
		g.ind--
		g.line("}")
		g.ind--
		g.line("}")
	}
}

func (g *gen) ret(s *ast.ReturnStmt) {
	fn := g.fn
	switch {
	case fn.Main:
		g.release()
		g.line("return 0;")
	case s.ErrTag != "":
		g.release()
		g.line("return QE_%s;", s.ErrTag)
	case s.Value != nil && fn.Fallible():
		g.line("*ql_out = %s;", g.exprAs(s.Value, fn.Ret))
		g.release()
		g.line("return 0;")
	case s.Value != nil:
		v := g.exprAs(s.Value, fn.Ret)
		if fn.DataFrame > 0 {
			r := g.temp(g.ctype(fn.Ret), v)
			g.release()
			g.line("return %s;", r)
		} else {
			g.line("return %s;", v)
		}
	case fn.Fallible():
		g.release()
		g.line("return 0;")
	default:
		g.release()
		g.line("return;")
	}
}

// ---- assignment ------------------------------------------------------------

func (g *gen) assign(s *ast.AssignStmt) {
	lt := s.LHS.Info().Type
	if f, ok := unparen(s.LHS).(*ast.Field); ok && f.Kind == ast.FieldBits {
		reg := g.lvalue(f.X)
		var v string
		if s.Op == "=" {
			v = g.exprAs(s.RHS, lt)
		} else {
			cur := g.bitsRead(reg, f.Bits)
			v = g.compound(s, cur, lt)
		}
		mask := fmt.Sprintf("0x%Xu", (uint64(1)<<f.Bits.Width)-1)
		g.line("%s = (%s & ~(%s << %d)) | (((uint32_t)(%s) & %s) << %d);", reg, reg, mask, f.Bits.Bit, v, mask, f.Bits.Bit)
		return
	}
	lv := g.lvalue(s.LHS)
	if s.Op == "=" {
		g.line("%s = %s;", lv, g.exprAs(s.RHS, lt))
		return
	}
	g.line("%s = %s;", lv, g.compound(s, lv, lt))
}

func (g *gen) compound(s *ast.AssignStmt, cur string, lt *types.Type) string {
	op := strings.TrimSuffix(s.Op, "=")
	rhs := g.exprAs(s.RHS, lt)
	if op == "<<" || op == ">>" {
		return g.shiftOp(op, cur, rhs, lt, s.Check)
	}
	return g.arith(op, cur, rhs, lt, s.Check)
}

// lvalue renders an assignable place without hoisting register reads.
func (g *gen) lvalue(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Paren:
		return g.lvalue(x.X)
	case *ast.Ident:
		return x.Sym.CName
	case *ast.Field:
		switch x.Kind {
		case ast.FieldStruct:
			return g.lvalue(x.X) + "." + check.CName(x.Name)
		case ast.FieldReg:
			return g.regsPtr(x.X) + "->" + x.Reg.Name
		}
	case *ast.Index:
		return g.indexPlace(x, true)
	}
	return g.expr(e)
}

func (g *gen) regsPtr(e ast.Expr) string {
	if id, ok := unparen(e).(*ast.Ident); ok {
		return id.Sym.CName
	}
	return g.expr(e)
}

func (g *gen) growPtr(e ast.Expr) string {
	if id, ok := unparen(e).(*ast.Ident); ok && id.Sym != nil {
		if id.Sym.Kind == types.SymGlobal {
			return "(&" + id.Sym.CName + ")"
		}
		return id.Sym.CName
	}
	return g.expr(e)
}

// addressable reports whether e names storage (so it can be viewed).
func addressable(e ast.Expr) bool {
	switch x := e.(type) {
	case *ast.Paren:
		return addressable(x.X)
	case *ast.Ident:
		return x.Sym != nil && (x.Sym.Kind == types.SymLocal || x.Sym.Kind == types.SymParam || x.Sym.Kind == types.SymGlobal || x.Sym.Kind == types.SymConst)
	case *ast.Field:
		return x.Kind == ast.FieldStruct && addressable(x.X)
	case *ast.Index:
		t := x.X.Info().Type
		return t.Kind == types.Slice || t.Kind == types.Grow || addressable(x.X)
	}
	return false
}

func (g *gen) indexPlace(x *ast.Index, place bool) string {
	t := x.X.Info().Type
	var base string
	switch t.Kind {
	case types.Array:
		if addressable(x.X) {
			base = g.lvalue(x.X)
		} else {
			base = g.expr(x.X)
		}
	case types.Grow:
		base = g.growPtr(x.X)
	default:
		base = g.expr(x.X)
	}
	idx := g.expr(x.I)
	if place && !stable(x.I) {
		idx = g.temp("uint32_t", idx)
	}
	switch t.Kind {
	case types.Array:
		if x.Info().Check {
			idx = fmt.Sprintf("ql_idx(%s, %du)", idx, t.Len)
		}
		return fmt.Sprintf("%s.a[%s]", base, idx)
	case types.Slice:
		if !stableStr(base) {
			base = g.temp(g.ctype(t), base)
		}
		if x.Info().Check {
			idx = fmt.Sprintf("ql_idx(%s, %s.len)", idx, base)
		}
		return fmt.Sprintf("%s.ptr[%s]", base, idx)
	case types.Grow:
		if x.Info().Check {
			idx = fmt.Sprintf("ql_idx(%s, %s->len)", idx, base)
		}
		return fmt.Sprintf("%s->data[%s]", base, idx)
	}
	return base
}

// stable reports whether evaluating e later gives the same value as now:
// constants and scalar or struct locals (callees cannot reach them).
func stable(e ast.Expr) bool {
	if e.Info().Const != nil {
		return true
	}
	switch x := e.(type) {
	case *ast.Paren:
		return stable(x.X)
	case *ast.BoolLit, *ast.EnumLit:
		return true
	case *ast.Ident:
		if x.Sym == nil {
			return false
		}
		switch x.Sym.Kind {
		case types.SymLocal, types.SymParam:
			switch x.Sym.Type.Kind {
			case types.Int, types.Bool, types.Enum, types.ErrorVal, types.Struct, types.Slice, types.Regs:
				return true
			}
		case types.SymErr, types.SymPeriph, types.SymConst:
			return true
		}
	case *ast.Field:
		return x.Kind == ast.FieldStruct && stable(x.X) || x.Kind == ast.FieldEnum
	}
	return false
}

func stableStr(s string) bool {
	for _, c := range s {
		if !(c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9') {
			return false
		}
	}
	return s != ""
}

// ---- expression statements -------------------------------------------------

func (g *gen) exprStmt(e ast.Expr) {
	switch x := e.(type) {
	case *ast.Call:
		switch x.Kind {
		case ast.CallFn:
			g.line("%s;", g.callExpr(x))
			return
		case ast.CallPush:
			gp := g.growPtr(x.Recv)
			v := g.exprAs(x.Args[0], x.Recv.Info().Type.Elem)
			if x.Info().Check {
				g.line("QL_CHECK(%s->len < %du);", gp, x.Recv.Info().Type.Len)
			}
			g.line("%s->data[%s->len++] = %s;", gp, gp, v)
			return
		case ast.CallClear:
			g.line("%s->len = 0;", g.growPtr(x.Recv))
			return
		}
	case *ast.Try:
		g.try(x)
		return
	case *ast.Catch:
		if x.Body != nil {
			call, _ := g.fallible(x.X)
			if x.ErrSym != nil {
				g.line("{")
				g.ind++
				g.line("const ql_err %s = %s;", x.ErrSym.CName, call)
				g.line("if (%s) {", x.ErrSym.CName)
			} else {
				g.line("if (%s) {", call)
			}
			g.ind++
			g.block(x.Body)
			g.ind--
			g.line("}")
			if x.ErrSym != nil {
				g.ind--
				g.line("}")
			}
			return
		}
		g.catchExpr(x)
		return
	}
	g.line("(void)(%s);", g.expr(e))
}

// ---- expressions -----------------------------------------------------------

// exprAs renders e for a context expecting type to: arrays and grow arrays
// become slice views where a slice is expected.
func (g *gen) exprAs(e ast.Expr, to *types.Type) string {
	from := e.Info().Type
	if to != nil && to.Kind == types.Slice && from != nil {
		st := g.ctype(to)
		switch from.Kind {
		case types.Array:
			if rootConst(e) {
				// Only for-each loops view constants, and they only read.
				return fmt.Sprintf("(%s){ (%s *)%s.a, %du }", st, g.ctype(from.Elem), g.lvalue(e), from.Len)
			}
			return fmt.Sprintf("(%s){ %s.a, %du }", st, g.lvalue(e), from.Len)
		case types.Grow:
			gp := g.growPtr(e)
			return fmt.Sprintf("(%s){ %s->data, %s->len }", st, gp, gp)
		}
	}
	if to != nil && from != nil && from.Kind == types.UntypedInt && e.Info().Const != nil && to.Kind == types.Int {
		return lit(e.Info().Const, to)
	}
	return g.expr(e)
}

func rootConst(e ast.Expr) bool {
	switch x := e.(type) {
	case *ast.Paren:
		return rootConst(x.X)
	case *ast.Ident:
		return x.Sym != nil && x.Sym.Kind == types.SymConst
	case *ast.Field:
		return rootConst(x.X)
	case *ast.Index:
		return rootConst(x.X)
	}
	return false
}

func (g *gen) expr(e ast.Expr) string {
	in := e.Info()
	if in.Const != nil {
		switch x := e.(type) {
		case *ast.EnumLit:
			return fmt.Sprintf("qn_%s_%s", in.Type.Name, x.Name)
		case *ast.Field:
			if x.Kind == ast.FieldEnum {
				return fmt.Sprintf("qn_%s_%s", in.Type.Name, x.Name)
			}
		}
		return lit(in.Const, in.Type)
	}
	switch x := e.(type) {
	case *ast.BoolLit:
		if x.Val {
			return "true"
		}
		return "false"
	case *ast.Paren:
		return "(" + g.expr(x.X) + ")"
	case *ast.Ident:
		if x.Sym == nil {
			return "0"
		}
		return x.Sym.CName
	case *ast.Unary:
		return g.unary(x)
	case *ast.Binary:
		return g.binary(x)
	case *ast.Call:
		return g.call(x)
	case *ast.Index:
		return g.indexPlace(x, false)
	case *ast.SliceExpr:
		return g.slice(x)
	case *ast.Field:
		return g.field(x)
	case *ast.Try:
		return g.try(x)
	case *ast.Catch:
		return g.catchExpr(x)
	case *ast.StructLit:
		var fs []string
		vals := g.seq(structVals(x), structTypes(x, in.Type))
		for i, fi := range x.Fields {
			fs = append(fs, fmt.Sprintf(".%s = %s", check.CName(fi.Name), vals[i]))
		}
		if len(fs) == 0 {
			return fmt.Sprintf("(%s){0}", g.ctype(in.Type))
		}
		return fmt.Sprintf("(%s){ %s }", g.ctype(in.Type), strings.Join(fs, ", "))
	case *ast.ArrayLit:
		ts := make([]*types.Type, len(x.Elems))
		for i := range ts {
			ts[i] = in.Type.Elem
		}
		vals := g.seq(x.Elems, ts)
		return fmt.Sprintf("(%s){{ %s }}", g.ctype(in.Type), strings.Join(vals, ", "))
	}
	return "0"
}

func structVals(x *ast.StructLit) []ast.Expr {
	var es []ast.Expr
	for _, f := range x.Fields {
		es = append(es, f.Value)
	}
	return es
}

func structTypes(x *ast.StructLit, t *types.Type) []*types.Type {
	var ts []*types.Type
	for _, fi := range x.Fields {
		var ft *types.Type
		for _, f := range t.Fields {
			if f.Name == fi.Name {
				ft = f.Type
			}
		}
		ts = append(ts, ft)
	}
	return ts
}

// seq renders operands left to right. If a later operand needs hoisted
// statements, earlier unstable operands are pinned to temporaries first so
// they are read before the later operand's side effects.
func (g *gen) seq(es []ast.Expr, ts []*types.Type) []string {
	vals := make([]string, len(es))
	for i, e := range es {
		var v string
		pre := g.captureFlat(func() { v = g.exprAs(e, ts[i]) })
		if pre != "" {
			for j := 0; j < i; j++ {
				if !stable(es[j]) && !stableStr(vals[j]) {
					t := ts[j]
					if t == nil || t.Kind == types.UntypedInt {
						t = es[j].Info().Type
					}
					if t.Kind == types.UntypedInt {
						t = types.IntT(64, true)
					}
					vals[j] = g.temp(g.ctype(t), vals[j])
				}
			}
			g.out.WriteString(pre)
		}
		vals[i] = v
	}
	return vals
}

// captureFlat is capture without the extra indent.
func (g *gen) captureFlat(f func()) string {
	g.ind--
	s := g.capture(f)
	g.ind++
	return s
}

func (g *gen) unary(x *ast.Unary) string {
	t := x.Info().Type
	v := g.expr(x.X)
	switch x.Op {
	case "!":
		return "(!" + v + ")"
	case "-":
		ct := g.ctype(t)
		if x.Info().Check {
			if t.Bits <= 32 {
				return fmt.Sprintf("((%s)ql_rng(-(int64_t)(%s), %s, %s))", ct, v, minLit(t), maxLit(t))
			}
			return fmt.Sprintf("((%s)ql_sub_s64(0, (int64_t)(%s), %s, %s))", ct, v, minLit(t), maxLit(t))
		}
		return fmt.Sprintf("((%s)(-(%s)))", ct, v)
	case "~":
		ct := g.ctype(t)
		if t.Signed {
			return fmt.Sprintf("((%s)(~(%s)))", ct, v)
		}
		uw := "uint32_t"
		if t.Bits > 32 {
			uw = "uint64_t"
		}
		return fmt.Sprintf("((%s)(~(%s)(%s) & %s))", ct, uw, v, maxLit(t))
	}
	return v
}

// operandType is the type both operands of a binary operator convert to.
func operandType(x, y *types.Type) *types.Type {
	if x.Kind == types.UntypedInt {
		return y
	}
	if y.Kind == types.UntypedInt {
		return x
	}
	if types.Widens(x, y) {
		return y
	}
	return x
}

func (g *gen) binary(b *ast.Binary) string {
	switch b.Op {
	case "&&", "||":
		l := g.expr(b.X)
		var r string
		pre := g.capture(func() { r = g.expr(b.Y) })
		if pre == "" {
			return fmt.Sprintf("(%s %s %s)", l, b.Op, r)
		}
		t := g.temp("bool", l)
		if b.Op == "&&" {
			g.line("if (%s) {", t)
		} else {
			g.line("if (!%s) {", t)
		}
		g.out.WriteString(pre)
		g.ind++
		g.line("%s = %s;", t, r)
		g.ind--
		g.line("}")
		return t
	}
	ot := operandType(b.X.Info().Type, b.Y.Info().Type)
	if ot.Kind == types.UntypedInt {
		ot = types.IntT(64, true)
	}
	vals := g.seq([]ast.Expr{b.X, b.Y}, []*types.Type{ot, ot})
	l, r := vals[0], vals[1]
	switch b.Op {
	case "==", "!=", "<", "<=", ">", ">=":
		if ot.Kind == types.Int {
			ct := g.ctype(ot)
			return fmt.Sprintf("((%s)(%s) %s (%s)(%s))", ct, l, b.Op, ct, r)
		}
		return fmt.Sprintf("(%s %s %s)", l, b.Op, r)
	case "<<", ">>":
		return g.shiftOp(b.Op, l, r, b.Info().Type, b.Info().Check)
	}
	return g.arith(b.Op, l, r, b.Info().Type, b.Info().Check)
}

// wrapRaw reduces a raw unsigned C value to type t modulo 2^bits.
func (g *gen) wrapRaw(raw string, t *types.Type) string {
	ct := g.ctype(t)
	std := t.Bits == types.CBits(t.Bits)
	switch {
	case !t.Signed && std:
		return fmt.Sprintf("((%s)(%s))", ct, raw)
	case !t.Signed:
		return fmt.Sprintf("((%s)((%s) & %s))", ct, raw, maxLit(t))
	case std:
		return fmt.Sprintf("((%s)(%s)(%s))", ct, intC(t.Bits, false), raw)
	}
	return fmt.Sprintf("((%s)ql_sext((uint64_t)(%s), %d))", ct, raw, t.Bits)
}

// arith renders a binary arithmetic or bitwise operation on values of t.
func (g *gen) arith(op, a, b string, t *types.Type, checked bool) string {
	ct := g.ctype(t)
	wide := t.Bits > 32
	uw := "uint32_t"
	if wide {
		uw = "uint64_t"
	}
	switch op {
	case "+", "-", "*":
		if !checked {
			return fmt.Sprintf("((%s)((%s)(%s) %s (%s)(%s)))", ct, ct, a, op, ct, b)
		}
		if !wide {
			if op == "*" && !t.Signed {
				return fmt.Sprintf("((%s)ql_rngu((uint64_t)(%s) * (uint64_t)(%s), %s))", ct, a, b, maxLit(t))
			}
			return fmt.Sprintf("((%s)ql_rng((int64_t)(%s) %s (int64_t)(%s), %s, %s))", ct, a, op, b, minLit(t), maxLit(t))
		}
		name := map[string]string{"+": "add", "-": "sub", "*": "mul"}[op]
		if t.Signed {
			return fmt.Sprintf("((%s)ql_%s_s64((int64_t)(%s), (int64_t)(%s), %s, %s))", ct, name, a, b, minLit(t), maxLit(t))
		}
		return fmt.Sprintf("((%s)ql_%s_u64((uint64_t)(%s), (uint64_t)(%s), %s))", ct, name, a, b, maxLit(t))
	case "/", "%":
		if !checked {
			return fmt.Sprintf("((%s)((%s)(%s) %s (%s)(%s)))", ct, ct, a, op, ct, b)
		}
		fn := map[string]string{"/": "div", "%": "mod"}[op]
		if t.Signed {
			return fmt.Sprintf("((%s)ql_rng(ql_%ss((int64_t)(%s), (int64_t)(%s)), %s, %s))", ct, fn, a, b, minLit(t), maxLit(t))
		}
		return fmt.Sprintf("((%s)ql_%su((uint64_t)(%s), (uint64_t)(%s)))", ct, fn, a, b)
	case "+%", "-%", "*%":
		return g.wrapRaw(fmt.Sprintf("(%s)(%s) %s (%s)(%s)", uw, a, op[:1], uw, b), t)
	case "+|", "-|", "*|":
		if !wide {
			if op == "*|" && !t.Signed {
				return fmt.Sprintf("((%s)ql_clampu((uint64_t)(%s) * (uint64_t)(%s), %s))", ct, a, b, maxLit(t))
			}
			return fmt.Sprintf("((%s)ql_clamp((int64_t)(%s) %s (int64_t)(%s), %s, %s))", ct, a, op[:1], b, minLit(t), maxLit(t))
		}
		name := map[string]string{"+|": "add", "-|": "sub", "*|": "mul"}[op]
		if t.Signed {
			return fmt.Sprintf("((%s)ql_s%s_s64((int64_t)(%s), (int64_t)(%s), %s, %s))", ct, name, a, b, minLit(t), maxLit(t))
		}
		return fmt.Sprintf("((%s)ql_s%s_u64((uint64_t)(%s), (uint64_t)(%s), %s))", ct, name, a, b, maxLit(t))
	case "&", "|", "^":
		return fmt.Sprintf("((%s)((%s)(%s) %s (%s)(%s)))", ct, ct, a, op, ct, b)
	}
	return "0"
}

func (g *gen) shiftOp(op, a, n string, t *types.Type, checked bool) string {
	if checked {
		n = fmt.Sprintf("ql_shamt(%s, %du)", n, t.Bits)
	}
	if op == "<<" {
		uw := "uint32_t"
		if t.Bits > 32 {
			uw = "uint64_t"
		}
		return g.wrapRaw(fmt.Sprintf("(%s)(%s) << %s", uw, a, n), t)
	}
	ct := g.ctype(t)
	return fmt.Sprintf("((%s)((%s)(%s) >> %s))", ct, ct, a, n)
}

// ---- calls -----------------------------------------------------------------

func (g *gen) args(x *ast.Call) []string {
	ts := make([]*types.Type, len(x.Args))
	for i := range x.Args {
		if x.Callee != nil && i < len(x.Callee.Params) {
			ts[i] = x.Callee.Params[i].Type
		}
	}
	vals := g.seq(x.Args, ts)
	if x.Callee != nil {
		for i, p := range x.Callee.Params {
			if i < len(vals) && p.Type.Kind == types.Grow {
				vals[i] = g.growPtr(x.Args[i])
			}
		}
	}
	return vals
}

// callExpr renders a non-fallible user or extern call.
func (g *gen) callExpr(x *ast.Call) string {
	return fmt.Sprintf("%s(%s)", x.Callee.CName, strings.Join(g.args(x), ", "))
}

func (g *gen) call(x *ast.Call) string {
	t := x.Info().Type
	switch x.Kind {
	case ast.CallFn:
		c := g.callExpr(x)
		if t.Kind == types.Void {
			g.line("%s;", c)
			return "0"
		}
		return g.temp(g.ctype(t), c)
	case ast.CallConvert, ast.CallWrap, ast.CallSat:
		return g.convert(x)
	}
	// push/clear/send/recv in expression position only occur as
	// statements or under ?/catch, which handle them.
	return "0"
}

func (g *gen) convert(x *ast.Call) string {
	t := x.Target
	a := x.Args[0]
	at := a.Info().Type
	v := g.expr(a)
	ct := g.ctype(t)
	switch x.Kind {
	case ast.CallConvert:
		if !x.Info().Check {
			return fmt.Sprintf("((%s)(%s))", ct, v)
		}
		if at.Kind == types.Enum {
			at = at.Base
		}
		if at.Kind == types.Int && !at.Signed {
			return fmt.Sprintf("((%s)ql_rngu((uint64_t)(%s), %s))", ct, v, maxLit(t))
		}
		return fmt.Sprintf("((%s)ql_rng((int64_t)(%s), %s, %s))", ct, v, minLit(t), maxS(t))
	case ast.CallWrap:
		return g.wrapRaw(fmt.Sprintf("(uint64_t)(%s)", v), t)
	case ast.CallSat:
		if at.Kind == types.Int && !at.Signed {
			return fmt.Sprintf("((%s)ql_clampu((uint64_t)(%s), %s))", ct, v, maxLit(t))
		}
		return fmt.Sprintf("((%s)ql_clamp((int64_t)(%s), %s, %s))", ct, v, minLit(t), maxS(t))
	}
	return v
}

// maxS is t's maximum as a signed 64-bit literal, capped at INT64_MAX, for
// the int64 helpers (ql_rng, ql_clamp).
func maxS(t *types.Type) string {
	m := t.Max()
	if m.Cmp(int64Max) > 0 {
		m = int64Max
	}
	return lit(m, types.IntT(64, true))
}

// fallible renders a fallible call as a C expression yielding ql_err; the
// value (if any) lands in the returned temporary.
func (g *gen) fallible(e ast.Expr) (call, out string) {
	x, ok := unparen(e).(*ast.Call)
	if !ok {
		return "0", ""
	}
	ut := e.Info().Type
	if ut.Kind == types.Union && ut.Elem.Kind != types.Void {
		out = g.temp(g.ctype(ut.Elem), zeroInit(ut.Elem))
	}
	switch x.Kind {
	case ast.CallFn:
		args := g.args(x)
		if out != "" {
			args = append(args, "&"+out)
		}
		return fmt.Sprintf("%s(%s)", x.Callee.CName, strings.Join(args, ", ")), out
	case ast.CallSend:
		qt := x.Recv.Info().Type
		v := g.exprAs(x.Args[0], qt.Elem)
		return fmt.Sprintf("ql_qsend_%s(&%s, %s)", mangle(qt), g.regsPtr(x.Recv), v), out
	case ast.CallRecv:
		qt := x.Recv.Info().Type
		return fmt.Sprintf("ql_qrecv_%s(&%s, &%s)", mangle(qt), g.regsPtr(x.Recv), out), out
	}
	return "0", out
}

func (g *gen) try(x *ast.Try) string {
	call, out := g.fallible(x.X)
	g.line("{")
	g.ind++
	g.line("const ql_err ql_e = %s;", call)
	g.line("if (ql_e) {")
	g.ind++
	g.release()
	g.line("return ql_e;")
	g.ind--
	g.line("}")
	g.ind--
	g.line("}")
	if out == "" {
		return "0"
	}
	return out
}

func (g *gen) catchExpr(x *ast.Catch) string {
	call, out := g.fallible(x.X)
	g.line("if (%s) {", call)
	g.ind++
	switch {
	case x.Default != nil:
		g.line("%s = %s;", out, g.exprAs(x.Default, x.Info().Type))
	case x.Jump != nil:
		g.stmt(x.Jump)
	}
	g.ind--
	g.line("}")
	if out == "" {
		return "0"
	}
	return out
}

// ---- selectors and slices --------------------------------------------------

func (g *gen) bitsRead(reg string, bf *types.BitField) string {
	mask := fmt.Sprintf("0x%Xu", (uint64(1)<<bf.Width)-1)
	raw := fmt.Sprintf("((%s >> %d) & %s)", reg, bf.Bit, mask)
	if bf.Type.Kind == types.Bool {
		return "(" + raw + " != 0u)"
	}
	return fmt.Sprintf("((%s)%s)", g.ctype(bf.Type), raw)
}

func (g *gen) field(x *ast.Field) string {
	switch x.Kind {
	case ast.FieldStruct:
		if addressable(x.X) {
			return g.lvalue(x.X) + "." + check.CName(x.Name)
		}
		return g.expr(x.X) + "." + check.CName(x.Name)
	case ast.FieldReg:
		// Hoist the volatile read so it happens once, in source order.
		return g.temp(intC(x.Reg.Type.Bits, false), g.regsPtr(x.X)+"->"+x.Reg.Name)
	case ast.FieldBits:
		reg := g.expr(x.X) // hoisted register read
		return g.bitsRead(reg, x.Bits)
	case ast.FieldLen:
		t := x.X.Info().Type
		switch t.Kind {
		case types.Grow:
			return g.growPtr(x.X) + "->len"
		case types.Slice:
			return g.expr(x.X) + ".len"
		}
	}
	return "0"
}

func (g *gen) slice(x *ast.SliceExpr) string {
	t := x.X.Info().Type
	st := g.ctype(x.Info().Type)
	var ptr, n string
	switch t.Kind {
	case types.Array:
		ptr = g.lvalue(x.X) + ".a"
		n = fmt.Sprintf("%du", t.Len)
	case types.Grow:
		gp := g.growPtr(x.X)
		ptr, n = gp+"->data", gp+"->len"
	case types.Slice:
		s := g.expr(x.X)
		if !stableStr(s) {
			s = g.temp(g.ctype(t), s)
		}
		ptr, n = s+".ptr", s+".len"
	}
	lo, hi := "0u", n
	var es []ast.Expr
	var ts []*types.Type
	if x.Lo != nil {
		es, ts = append(es, x.Lo), append(ts, types.Usize)
	}
	if x.Hi != nil {
		es, ts = append(es, x.Hi), append(ts, types.Usize)
	}
	vals := g.seq(es, ts)
	if x.Lo != nil {
		lo = vals[0]
		vals = vals[1:]
	}
	if x.Hi != nil {
		hi = vals[0]
	}
	if x.Info().Check {
		if !stableStr(lo) {
			lo = g.temp("uint32_t", lo)
		}
		if !stableStr(hi) {
			hi = g.temp("uint32_t", hi)
		}
		g.line("QL_CHECK(%s <= %s && %s <= %s);", lo, hi, hi, n)
	}
	return fmt.Sprintf("(%s){ %s + %s, (uint32_t)(%s - %s) }", st, ptr, lo, hi, lo)
}

func unparen(e ast.Expr) ast.Expr {
	for {
		p, ok := e.(*ast.Paren)
		if !ok {
			return e
		}
		e = p.X
	}
}

// terminates mirrors the checker's rule for falling off a function's end.
func terminates(s ast.Stmt) bool {
	switch x := s.(type) {
	case *ast.Block:
		return len(x.Stmts) > 0 && terminates(x.Stmts[len(x.Stmts)-1])
	case *ast.ReturnStmt:
		return true
	case *ast.IfStmt:
		return x.Else != nil && terminates(x.Then) && terminates(x.Else)
	case *ast.ForStmt:
		return x.Kind == ast.ForEver && !hasBreak(x.Body)
	}
	return false
}

func hasBreak(b *ast.Block) bool {
	for _, s := range b.Stmts {
		switch x := s.(type) {
		case *ast.BranchStmt:
			if x.Tok == "break" {
				return true
			}
		case *ast.IfStmt:
			if hasBreak(x.Then) {
				return true
			}
			for e := x.Else; e != nil; {
				switch el := e.(type) {
				case *ast.Block:
					if hasBreak(el) {
						return true
					}
					e = nil
				case *ast.IfStmt:
					if hasBreak(el.Then) {
						return true
					}
					e = el.Else
				default:
					e = nil
				}
			}
		case *ast.Block:
			if hasBreak(x) {
				return true
			}
		}
		for _, e := range ast.StmtExprs(s) {
			found := false
			ast.WalkExpr(e, func(e ast.Expr) bool {
				if c, ok := e.(*ast.Catch); ok {
					if br, ok := c.Jump.(*ast.BranchStmt); ok && br.Tok == "break" {
						found = true
					}
					if c.Body != nil && hasBreak(c.Body) {
						found = true
					}
				}
				return !found
			})
			if found {
				return true
			}
		}
	}
	return false
}
